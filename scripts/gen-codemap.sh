#!/usr/bin/env bash
# Generates docs/engineering/codemap.md: exported symbols per Go package and TS package.
# Agents read the code map instead of searching the codebase. Run after each merge.
set -euo pipefail
cd "$(dirname "$0")/.."
out=docs/engineering/codemap.md
{
  echo "# Code map (generated by scripts/gen-codemap.sh, do not edit)"
  echo
  echo "## Go packages (apps/api)"
  (cd apps/api && for pkg in $(go list ./... | grep -v -e /dbgen -e /outboxtest -e /schedulertest); do
    rel=${pkg#github.com/NandanMaheta/swastik/apps/api/}
    syms=$(go doc -short "$pkg" 2>/dev/null | sed 's/^/    /' || true)
    [ -n "$syms" ] && { echo; echo "### \`$rel\`"; echo; echo '```go'; echo "$syms" | sed 's/^    //'; echo '```'; }
  done)
  echo
  echo "## TypeScript packages"
  for f in packages/*/src/index.ts; do
    echo; echo "### \`$(dirname "$(dirname "$f")")\`"; echo; echo '```ts'
    grep -hE '^export ' "$(dirname "$f")"/*.ts 2>/dev/null | grep -v test | sed 's/ {$//' | head -60
    echo '```'
  done
} > "$out"
echo "wrote $out"
